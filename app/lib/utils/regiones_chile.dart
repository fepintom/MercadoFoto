  /// Región en que cae un punto, o null si está lejos de todo lugar de
  /// referencia (datos malos, o fuera de Chile).
  static String? regionDe(double lat, double lng) {
    final cosLat = math.cos(lat * math.pi / 180);
    double mejor = double.infinity;
    int? idx;
    for (final (clat, clng, r) in _ciudades) {
      final dy = lat - clat;
      final dx = (lng - clng) * cosLat;
      final d = dx * dx + dy * dy;
      if (d < mejor) {
        mejor = d;
        idx = r;
      }
    }
    // ~2.5 grados ≈ 280 km: más lejos que eso, no es un dato confiable.
    if (idx == null || mejor > 2.5 * 2.5) return null;
    return nombres[idx];
  }

  /// Puntos de referencia de una región: sirven para encuadrar el mapa
  /// cuando el usuario elige esa región.
  static List<(double, double)> puntosDe(String region) {
    final idx = nombres.indexOf(region);
    if (idx < 0) return const [];
    return [
      for (final (lat, lng, r) in _ciudades)
        if (r == idx) (lat, lng),
    ];
  }

  /// Igual que [regionDe] pero leyendo lat/lng de un mapa de la API.
  static String? regionDeItem(Map item) {
    final lat = item['lat'], lng = item['lng'];
    if (lat is! num || lng is! num) return null;
    return regionDe(lat.toDouble(), lng.toDouble());
  }
